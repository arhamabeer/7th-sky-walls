/* 5. A composed group of value words                                         */
/* ------------------------------------------------------------------------- */

/** Values or team words as one composed group, with a single word in the accent. */
export function valuesBoard(r, w, h, p, { words }) {
  const { depth, stepX, stepY, shadowOffset } = depthFor(w);
  const face = FACES.heavy;
  const list = words.slice(0, 6).map((x) => x.toUpperCase());
  const rowH = (h * 0.82) / list.length;
  const heroIndex = Math.floor(r() * list.length);
  let s = "";

  list.forEach((word, i) => {
    const isHero = i === heroIndex;
    const target = w * (isHero ? 0.86 : between(r, 0.52, 0.74));
    const size = Math.min(target / textWidth(word, 1, face), rowH * 0.74);
    const alignLeft = i % 2 === 0;
    s += raised(
      textLayer({
        x: alignLeft ? w * 0.08 : w * 0.92,
        y: h * 0.11 + rowH * i + size * capOf(face),
        size,
        face,
        anchor: alignLeft ? "start" : "end",
        str: word,
      }),
      {
        depth: isHero ? depth + 2 : depth,
        stepX,
        stepY,
        side: isHero ? p.accentSide : p.side,
        face: isHero ? p.accent : p.face,
        shadow: { x: shadowOffset, y: shadowOffset, colour: p.shadow, opacity: 0.3 },
      },
    );
  });
  return s;
}

