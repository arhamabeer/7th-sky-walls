/* 6. Brand wall — mark, wordmark, rule                                       */
/* ------------------------------------------------------------------------- */

/** A logo wall: abstract mark, wordmark and rule, all cut and mounted. */
export function brandWall(r, w, h, p, { title }) {
  const { depth, stepX, stepY, shadowOffset } = depthFor(w);
  const face = FACES.heavy;
  const word =
    String(title).replace(/[^A-Za-z0-9 ]/g, "").toUpperCase().trim() || "STUDIO";
  const cx = w / 2;
  let s = "";

  const mark = (d, accent) =>
    raised(pathLayer({ d, strokeWidth: Math.min(w * 0.17, h * 0.13) * 0.3 }), {
      depth,
      stepX,
      stepY,
      side: accent ? p.accentSide : p.side,
      face: accent ? p.accent : p.face,
      shadow: { x: shadowOffset, y: shadowOffset, colour: p.shadow, opacity: 0.3 },
    });

  const markR = Math.min(w * 0.17, h * 0.13);
  const markCy = h * 0.3;
  s += mark(`M ${cx - markR} ${markCy} a ${markR} ${markR} 0 0 1 ${markR * 2} 0`, false);
  s += mark(
    `M ${cx - markR * 0.52} ${markCy + markR * 0.52} ` +
      `a ${markR * 0.52} ${markR * 0.52} 0 0 0 ${markR * 1.04} 0`,
    true,
  );

  const size = Math.min((w * 0.8) / textWidth(word, 1, face, 0), h * 0.11);
  s += raised(
    textLayer({ x: cx, y: h * 0.6, size, face, tracking: size * 0.06, str: word }),
    {
      depth,
      stepX,
      stepY,
      side: p.side,
      face: p.face,
      shadow: { x: shadowOffset, y: shadowOffset, colour: p.shadow, opacity: 0.32 },
    },
  );

  s += raised(
    pathLayer({
      d: `M ${w * 0.3} ${h * 0.7} H ${w * 0.7}`,
      strokeWidth: h * 0.01,
      cap: "butt",
    }),
    {
      depth: Math.max(3, depth - 2),
      stepX,
      stepY,
      side: p.accentSide,
      face: p.accent,
      shadow: { x: shadowOffset * 0.7, y: shadowOffset * 0.7, colour: p.shadow, opacity: 0.26 },
    },
  );
  return s;
}
