/* 3. Outline line-art bulbs on wires                                         */
/* ------------------------------------------------------------------------- */

/**
 * Bulbs drawn as continuous outline on hanging wires, each carrying one word.
 * Stroke only, never filled: these are printed as a filament line, and a solid
 * shape would misrepresent what arrives.
 */
export function lineArtBulbs(r, w, h, p, { words }) {
  // The word inside the ring is set condensed, not in the heavy face: at six
  // bulbs across a wall these are the only legible option — the heavy face put
  // "INNOVATION" at a fifth of the ring's width and it read as a smudge.
  const face = FACES.condensed;
  const step = Math.max(1.2, w * 0.0022);
  const n = clamp(words.length, 4, 6);
  const slot = w / n;
  const stroke = Math.max(3, w * 0.0095);
  let s = "";

  for (let i = 0; i < n; i += 1) {
    const colour = p.line[i % p.line.length];
    const side = p.lineSide[i % p.lineSide.length];
    const cx = slot * (i + 0.5);
    // Alternating drops so the row reads as hung rather than ruled.
    const drop = h * (i % 2 === 0 ? 0.34 : 0.52);
    const bulbR = Math.min(slot * 0.42, h * 0.17);
    const bulbCy = drop + bulbR * 1.15;

    const wire =
      `M ${cx} 0 C ${cx + slot * 0.12} ${drop * 0.3}, ` +
      `${cx - slot * 0.12} ${drop * 0.62}, ${cx} ${drop}`;
    const coil = Array.from({ length: 4 }, (_, k) => {
      const cyk = drop + (bulbR * 0.28 * k) / 2;
      return `M ${cx - bulbR * 0.3} ${cyk} q ${bulbR * 0.3} ${bulbR * 0.16}, ${bulbR * 0.6} 0`;
    }).join(" ");
    const glass = circlePath(cx, bulbCy, bulbR);

    const drawGroup = (dx, dy, c, opacity) =>
      `<g transform="translate(${dx.toFixed(1)} ${dy.toFixed(1)})" fill="none" stroke="${c}" ` +
      `stroke-width="${stroke.toFixed(1)}" stroke-linecap="round"` +
      `${opacity !== 1 ? ` opacity="${opacity}"` : ""}>` +
      `<path d="${wire}"/><path d="${coil}"/><path d="${glass}"/></g>`;

    s += raised(drawGroup, {
      depth: 4,
      stepX: step,
      stepY: step,
      side,
      face: colour,
      shadow: { x: step * 6, y: step * 6, colour: p.shadow, opacity: 0.26 },
    });

    const word = words[i % words.length].toUpperCase();
    const size = Math.min((bulbR * 1.7) / textWidth(word, 1, face), bulbR * 0.5);
    s += raised(
      textLayer({ x: cx, y: bulbCy + size * capOf(face) * 0.5, size, face, str: word }),
      {
        depth: 3,
        stepX: step,
        stepY: step,
        side,
        face: colour,
        shadow: { x: step * 4, y: step * 4, colour: p.shadow, opacity: 0.22 },
      },
    );
  }
  return s;
}

