/* 2. A single statement at monumental scale                                  */
/* ------------------------------------------------------------------------- */

/**
 * One line stacked into words, optionally carrying the noughts-and-crosses
 * motif that the "think outside the box" pieces are built around.
 */
export function statementLines(r, w, h, p, { title, motif }) {
  const { depth, stepX, stepY, shadowOffset } = depthFor(w);
  const face = FACES.heavy;
  const words = String(title)
    .replace(/[^A-Za-z0-9' ]/g, " ")
    .split(/\s+/)
    .filter(Boolean)
    .map((x) => x.toUpperCase());
  if (!words.length) return "";

  const motifH = motif ? h * 0.3 : 0;
  const blockH = h - motifH - h * 0.14;
  const maxWidth = w * 0.84;

  /**
   * Choose the line breaks that let the type be largest.
   *
   * One word per line is right for a portrait and wrong for a panorama: three
   * stacked words in a 5:2 box are each a third of the height, and they ran off
   * the bottom. So every split from one line up to one-word-per-line is costed
   * against both the width and the height, and the biggest that fits wins.
   */
  const layoutFor = (lineCount) => {
    const perLine = Math.ceil(words.length / lineCount);
    const lines = [];
    for (let i = 0; i < words.length; i += perLine) {
      lines.push(words.slice(i, i + perLine).join(" "));
    }
    const widest = Math.max(...lines.map((line) => textWidth(line, 1, face)));
    const size = Math.min(maxWidth / widest, blockH / (lines.length * 1.14));
    return { lines, size };
  };

  let best = layoutFor(1);
  for (let n = 2; n <= words.length; n += 1) {
    const candidate = layoutFor(n);
    if (candidate.size > best.size) best = candidate;
  }
  const { lines, size } = best;
  const lineH = size * 1.14;
  const left = w * 0.08;
  let y = h * 0.07 + size * capOf(face);

  const faceRaise = (extra = 0, accent = false, shadowScale = 1) => ({
    depth: Math.max(3, depth + extra),
    stepX,
    stepY,
    side: accent ? p.accentSide : p.side,
    face: accent ? p.accent : p.face,
    shadow: {
      x: shadowOffset * shadowScale,
      y: shadowOffset * shadowScale,
      colour: p.shadow,
      opacity: 0.3,
    },
  });

  let s = "";
  for (const line of lines) {
    s += raised(textLayer({ x: left, y, size, face, anchor: "start", str: line }), faceRaise());
    y += lineH;
  }

  if (motif) {
    const gridTop = h - motifH - h * 0.02;
    const gridSize = Math.min(w * 0.62, motifH);
    const gx = left;
    const cell = gridSize / 3;
    const bar = Math.max(4, gridSize * 0.028);

    for (let i = 1; i <= 2; i += 1) {
      s += raised(
        pathLayer({ d: `M ${gx + cell * i} ${gridTop} V ${gridTop + gridSize}`, strokeWidth: bar }),
        faceRaise(-2, false, 0.7),
      );
      s += raised(
        pathLayer({ d: `M ${gx} ${gridTop + cell * i} H ${gx + gridSize}`, strokeWidth: bar }),
        faceRaise(-2, false, 0.7),
      );
    }

    const marks = ["O", "X", "X", "X", "O", "O", "X", "O", "X"];
    const glyph = cell * 0.62;
    for (let i = 0; i < 9; i += 1) {
      const gcx = gx + cell * (i % 3) + cell / 2;
      const gcy = gridTop + cell * Math.floor(i / 3) + cell / 2;
      const d =
        marks[i] === "O"
          ? circlePath(gcx, gcy, glyph / 2)
          : `M ${gcx - glyph / 2} ${gcy - glyph / 2} L ${gcx + glyph / 2} ${gcy + glyph / 2} ` +
            `M ${gcx + glyph / 2} ${gcy - glyph / 2} L ${gcx - glyph / 2} ${gcy + glyph / 2}`;
      s += raised(pathLayer({ d, strokeWidth: bar * 0.9 }), faceRaise(-2, false, 0.6));
    }

    // The winning line struck through the grid, breaking it in the accent.
    s += raised(
      pathLayer({
        d: `M ${gx + cell * 1.5} ${gridTop - gridSize * 0.06} V ${gridTop + gridSize * 1.06}`,
        strokeWidth: bar * 1.5,
      }),
      faceRaise(0, true),
    );
  }

  return s;
}

