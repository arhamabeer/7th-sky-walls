/* 1. Word cloud packed into a lightbulb                                      */
/* ------------------------------------------------------------------------- */

/**
 * Words packed into a lightbulb silhouette with one hero word across the middle.
 *
 * Rows are measured against the actual chord of the glass at each height, so
 * the cloud takes the bulb's shape instead of being a rectangle with the
 * corners knocked off.
 */
export function wordCloudBulb(r, w, h, p, { words, hero }) {
  const { depth, stepX, stepY, shadowOffset } = depthFor(w);
  const face = FACES.condensed;
  let s = "";

  /**
   * Deal words without replacement, refilling only when the pool runs dry, and
   * never repeat the hero word among them. Picking at random with replacement
   * put the same word three times in one bulb, which reads as a fault rather
   * than as a composition.
   */
  const pool = words.filter((x) => x.toUpperCase() !== String(hero).toUpperCase());
  let bag = [];
  const deal = () => {
    if (!bag.length) {
      bag = [...pool];
      // Fisher-Yates, seeded from the same PRNG so the piece stays deterministic.
      for (let i = bag.length - 1; i > 0; i -= 1) {
        const j = Math.floor(r() * (i + 1));
        [bag[i], bag[j]] = [bag[j], bag[i]];
      }
    }
    return bag.pop();
  };

  const cx = w / 2;
  const glassR = Math.min(w * 0.45, h * 0.30);
  const cy = glassR + h * 0.045;
  const neckTop = cy + glassR * 0.8;
  const neckBottom = cy + glassR * 1.3;
  const baseTop = neckBottom;
  const baseH = h * 0.16;

  /** Half-width of the silhouette at a given height. */
  const halfWidthAt = (y) => {
    if (y <= cy + glassR) {
      const dy = Math.abs(y - cy);
      return dy >= glassR ? 0 : Math.sqrt(glassR * glassR - dy * dy);
    }
    const t = clamp((y - neckTop) / (neckBottom - neckTop), 0, 1);
    return glassR * (0.62 - 0.3 * t);
  };

  const heroSize = Math.min((glassR * 2 * 0.86) / textWidth(hero, 1, face), h * 0.22);
  const heroBandTop = cy - heroSize * 0.55;
  const heroBandBottom = cy + heroSize * 0.55;

  const rows = [];
  let y = cy - glassR + h * 0.012;
  while (y < neckBottom) {
    const rowH = between(r, h * 0.03, h * 0.052);
    const mid = y + rowH * 0.5;
    if (mid > heroBandTop - rowH * 0.3 && mid < heroBandBottom + rowH * 0.3) {
      y = heroBandBottom + rowH * 0.32;
      continue;
    }
    const available = halfWidthAt(mid) * 2 * 0.94;
    if (available > w * 0.06) rows.push({ mid, rowH, available });
    y += rowH * 1.04;
  }

  for (const row of rows) {
    const size = row.rowH / capOf(face);
    const gap = size * 0.26;
    const chosen = [];
    let used = 0;
    // Try several candidates per slot: a word that does not fit should not end
    // the row when a shorter one still would. Give up after enough misses.
    let misses = 0;
    const rejected = [];
    while (misses < 6 && chosen.length < 6) {
      const word = deal();
      const wd = textWidth(word, size, face);
      const needed = used + wd + (chosen.length ? gap : 0);
      if (needed > row.available) {
        // Too wide for what is left of this row, but still unused — hold it and
        // return it to the bag rather than dropping it from the piece.
        rejected.push(word);
        misses += 1;
        continue;
      }
      used = needed;
      chosen.push({ word, wd });
    }
    bag.push(...rejected);
    if (!chosen.length) continue;
    let x = cx - used / 2;
    for (const { word, wd } of chosen) {
      s += raised(
        textLayer({ x: x + wd / 2, y: row.mid + row.rowH * 0.5, size, face, str: word }),
        {
          depth,
          stepX,
          stepY,
          side: p.side,
          face: p.face,
          shadow: { x: shadowOffset, y: shadowOffset, colour: p.shadow, opacity: 0.3 },
        },
      );
      x += wd + gap;
    }
  }

  // The hero word, in the accent, standing proud of everything around it.
  s += raised(
    textLayer({ x: cx, y: cy + heroSize * capOf(face) * 0.5, size: heroSize, face, str: hero }),
    {
      depth: depth + 3,
      stepX,
      stepY,
      side: p.accentSide,
      face: p.accent,
      shadow: { x: shadowOffset * 1.3, y: shadowOffset * 1.3, colour: p.shadow, opacity: 0.34 },
    },
  );

  // Screw base: three bands and a tip, in the accent.
  const accentRaise = {
    depth,
    stepX,
    stepY,
    side: p.accentSide,
    face: p.accent,
    shadow: { x: shadowOffset, y: shadowOffset, colour: p.shadow, opacity: 0.28 },
  };
  const bandW = glassR * 0.62;
  for (let i = 0; i < 3; i += 1) {
    const by = baseTop + baseH * (0.06 + i * 0.24);
    const bh = baseH * 0.17;
    s += raised(
      pathLayer({
        d:
          `M ${cx - bandW / 2} ${by} h ${bandW} ` +
          `a ${bh / 2} ${bh / 2} 0 0 1 0 ${bh} h ${-bandW} ` +
          `a ${bh / 2} ${bh / 2} 0 0 1 0 ${-bh} z`,
        strokeWidth: 0,
        fill: "colour",
      }),
      accentRaise,
    );
  }
  const tipTop = baseTop + baseH * 0.78;
  s += raised(
    pathLayer({
      d:
        `M ${cx - bandW * 0.34} ${tipTop} L ${cx + bandW * 0.34} ${tipTop} ` +
        `L ${cx + bandW * 0.16} ${tipTop + baseH * 0.22} ` +
        `L ${cx - bandW * 0.16} ${tipTop + baseH * 0.22} z`,
      strokeWidth: 0,
      fill: "colour",
    }),
    accentRaise,
  );

  return s;
}

