/* 4. Raised calligraphic stroke                                              */
/* ------------------------------------------------------------------------- */

/**
 * A word cut as calligraphic letterforms, mounted proud of the wall, with an
 * underswept flourish. The word carries the piece; the flourish is trim.
 */
export function raisedScript(r, w, h, p, { word }) {
  const { depth, stepX, stepY, shadowOffset } = depthFor(w);
  const face = FACES.script;
  const text = String(word).trim() || "Sabr";
  const cx = w / 2;
  let s = "";

  const size = Math.min((w * 0.78) / textWidth(text, 1, face), h * 0.34);
  const baseline = h * 0.5 + size * capOf(face) * 0.3;

  s += raised(textLayer({ x: cx, y: baseline, size, face, str: text }), {
    depth: depth + 2,
    stepX,
    stepY,
    side: p.side,
    face: p.face,
    shadow: { x: shadowOffset * 1.2, y: shadowOffset * 1.2, colour: p.shadow, opacity: 0.32 },
  });

  // A single sweep under the word, in the accent, echoing a pen's exit stroke.
  const half = (textWidth(text, size, face) / 2) * 1.06;
  s += raised(
    pathLayer({
      d:
        `M ${cx - half} ${baseline + size * 0.24} ` +
        `C ${cx - half * 0.3} ${baseline + size * 0.42}, ` +
        `${cx + half * 0.3} ${baseline + size * 0.1}, ` +
        `${cx + half} ${baseline + size * 0.3}`,
      strokeWidth: size * 0.075,
    }),
    {
      depth,
      stepX,
      stepY,
      side: p.accentSide,
      face: p.accent,
      shadow: { x: shadowOffset, y: shadowOffset, colour: p.shadow, opacity: 0.28 },
    },
  );

  const dotR = size * 0.055;
  s += raised(
    pathLayer({
      d: circlePath(cx + half * 0.5, baseline - size * 0.92, dotR),
      strokeWidth: 0,
      fill: "colour",
    }),
    {
      depth,
      stepX,
      stepY,
      side: p.accentSide,
      face: p.accent,
      shadow: { x: shadowOffset, y: shadowOffset, colour: p.shadow, opacity: 0.28 },
    },
  );
  return s;
}

