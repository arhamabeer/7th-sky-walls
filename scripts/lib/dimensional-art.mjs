/**
 * Placeholder art for dimensional wall lettering.
 *
 * The studio's product is raised lettering and word-cloud panels cut from
 * acrylic, PVC foam, MDF or aluminium, or 3D-printed, and mounted on the wall —
 * not printed pictures. So these placeholders draw objects that sit on a wall
 * and cast shadows, rather than images sitting inside a frame.
 *
 * Everything is drawn with alpha and no ground. A dimensional piece has no
 * rectangular substrate: the letters ARE the artwork and the wall behind them
 * belongs to the room. The site paints each piece's specified wall tone behind
 * it; AR puts it on the visitor's real wall, where a pale piece on a pale wall
 * correctly disappears — which is the reason wall tone is specified at all.
 *
 * Two font stacks, both confirmed present on the build machine by measuring
 * rendered ink rather than trusting the name. "Arial Black" is deliberately
 * absent: it resolves to plain Arial here, silently changing every metric.
 */

import METRICS from "./font-metrics.json" with { type: "json" };

/** Escape text for inclusion in SVG markup. */
const xml = (s) =>
  String(s).replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" })[c],
  );

const between = (r, min, max) => min + r() * (max - min);
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

/**
 * Measured metrics, not guessed. Rendering "THINK" at 130px and measuring the
 * ink box produced these ratios; they are what makes the fitting arithmetic
 * land inside the canvas rather than near it.
 */
export const FACES = {
  /** Condensed heavy display — what a dense word cloud is actually set in. */
  condensed: {
    key: "condensed",
    family: "Impact, Haettenschweiler, 'Arial Narrow', sans-serif",
    weight: 400,
  },
  /** Heavy geometric sans, for a single statement at monumental scale. */
  heavy: {
    key: "heavy",
    family: "'Segoe UI Black', 'Segoe UI', Tahoma, sans-serif",
    weight: 900,
  },
  /**
   * Serif italic, standing in for cut calligraphic letterforms.
   *
   * A calligraphy piece is letters, so the placeholder has to be letters. An
   * earlier version drew abstract flowing strokes and read as decoration
   * rather than writing — which misrepresents the one collection where the
   * words are the whole point.
   */
  script: {
    key: "script",
    family: "Georgia, 'Times New Roman', serif",
    weight: 700,
    style: "italic",
  },
};

/** Cap height as a fraction of the font size, measured per face. */
const capOf = (face) => METRICS[face.key].cap;

/**
 * Width of a string at a given size, summed from measured per-character
 * advances.
 *
 * A single average advance was not good enough and the failure was visible: the
 * mean for the heavy face is 0.68 but "W" is 1.07, so words like ANYWAY and
 * BETTER were fitted as if they were as narrow as THINK and ran off the canvas.
 * The table in font-metrics.json is generated by rendering each character eight
 * times and measuring the ink, so this is arithmetic rather than a guess.
 */
function textWidth(str, size, face, tracking = 0) {
  const m = METRICS[face.key];
  let total = 0;
  for (const ch of String(str)) {
    total += (m.widths[ch] ?? m.space) * size;
  }
  return total + Math.max(0, String(str).length - 1) * tracking;
}

/**
 * Emit one element as a physical raised object: a stack of offset copies in the
 * side colour reading as the cut edge, the face on top, and a contact shadow
 * beneath. `draw(dx, dy, colour, opacity)` returns the SVG for one layer.
 */
function raised(draw, { depth, stepX, stepY, side, face, shadow }) {
  let s = "";
  if (shadow) s += draw(shadow.x, shadow.y, shadow.colour, shadow.opacity);
  for (let i = depth; i >= 1; i -= 1) s += draw(stepX * i, stepY * i, side, 1);
  return s + draw(0, 0, face, 1);
}

/** A text layer factory suitable for `raised`. */
const textLayer = ({ x, y, size, face, tracking = 0, anchor = "middle", str }) =>
  (dx, dy, colour, opacity) =>
    `<text x="${(x + dx).toFixed(1)}" y="${(y + dy).toFixed(1)}" ` +
    `font-family="${face.family}" font-size="${size.toFixed(1)}" font-weight="${face.weight}" ` +
    `${face.style ? `font-style="${face.style}" ` : ""}` +
    `letter-spacing="${tracking.toFixed(2)}" text-anchor="${anchor}" fill="${colour}"` +
    `${opacity !== 1 ? ` opacity="${opacity}"` : ""}>${xml(str)}</text>`;

/** A path layer factory suitable for `raised`. `fill: "colour"` fills instead of strokes. */
const pathLayer = ({ d, strokeWidth, cap = "round", fill = "none" }) =>
  (dx, dy, colour, opacity) =>
    `<path d="${d}" transform="translate(${dx.toFixed(1)} ${dy.toFixed(1)})" ` +
    `fill="${fill === "colour" ? colour : fill}" ` +
    `stroke="${fill === "colour" ? "none" : colour}" ` +
    `stroke-width="${strokeWidth.toFixed(1)}" stroke-linecap="${cap}" stroke-linejoin="round"` +
    `${opacity !== 1 ? ` opacity="${opacity}"` : ""}/>`;

/** Depth scaled to the canvas, so a small piece is not drawn with a giant edge. */
const depthFor = (w) => {
  const step = Math.max(1.5, w * 0.0035);
  return { depth: 6, stepX: step, stepY: step, shadowOffset: step * 7 };
};

/** A full circle as a single arc — `a r r 0 1 0 0.01 0` closes on itself. */
const circlePath = (cx, cy, r) => `M ${cx} ${cy - r} a ${r} ${r} 0 1 0 0.01 0 z`;

